class DisplayValue {
    public static void main(String[] args) {
        int a = 7;
        float b = 6.7f;
        double c = 6.789;
        char d = 'F';

        System.out.println("This is an integer no: " + a);
        System.out.println("This is a float no: " + b);
        System.out.println("This is a double no: " + c);
        System.out.println("This is a char no: " + d);
    }
}